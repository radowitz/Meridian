export type TrafficKey = "up_domestic" | "down_domestic" | "up_foreign" | "down_foreign";

/** Cumulative forwarded-throughput counters; rates are computed by the client between two samples. */
export interface TrafficView {
  available: boolean;
  read_at?: string;
  /** A counter went backwards or was replaced: this sample is a new baseline, not a rate. */
  reset: boolean;
  counter_epoch?: number;
  counters: Partial<Record<TrafficKey, { bytes: number; packets: number }>>;
  usage_bytes?: { domestic?: number; foreign?: number };
  missing?: string[];
  /** agent_unavailable | read_failed | not_installed */
  code?: string;
  message?: string;
  /** Active connections of LAN and remote-access devices through the gateway; null when the agent cannot report them. */
  connections?: TrafficConnections | null;
}

/** total = domestic + foreign + redirected; counts are null (never 0) when unknown. */
export interface TrafficConnections {
  available: boolean;
  read_at?: string;
  scope: "lan_and_remote_access";
  /** domestic/foreign are known (false: total only). */
  split: boolean;
  domestic: number | null;
  foreign: number | null;
  /** Sniff-forwarded TCP: side unknown to conntrack, counted in total only. */
  redirected: number | null;
  total: number | null;
  /** read_failed */
  code?: string;
  message?: string;
}
