// The host-level Linux connector (docs/architecture.md「主机级 Mesh 节点」).
//
// A host without a Mesh node gets the official cloudflare-warp package,
// registered as a connector of the panel's Mesh account. Every script here
// is fixed: its only inputs are the run id (hex), the node role, the
// release codename read from the detection (charset-checked), the pinned
// signing key fingerprint (40 hex) and, for the install alone, the node
// token (charset-checked). The token exists on the host only in a 0600 file
// inside a 0700 temporary directory that the script removes on every exit.
//
// Before the install mutates a resource (key, repo, package, service,
// registration) it persists an intent marker with the resource's prior
// state in the run's backup directory (a failed write stops the install);
// after the mutation a "created" marker follows and a MESH_CREATED line is
// echoed into the journal. The removal inspects the actual state of every
// resource with either marker and undoes only what this run added, one
// resource at a time, so a partial apt install, an enable that could not
// start, or an interruption between a command and its marker is still
// withdrawn. A registration that cannot be confirmed deleted keeps the
// client and all it depends on, and the removal reports incomplete.

const (
	ActConnectorPreflight Action = "connector_preflight"
	ActConnectorInstall   Action = "connector_install"
	ActConnectorRemove    Action = "connector_remove"
)

// Resources a connector install can create (OwnedRemote.Created).
var connectorResources = []string{"gnupg", "key", "repo", "package", "service", "registration"}

var (
	codenameRe   = regexp.MustCompile(`^[a-z][a-z0-9-]{1,23}$`)
	createdRe    = regexp.MustCompile(`(?m)^MESH_CREATED (gnupg|key|repo|package|service|registration)\s*$`)
	nodeAddrRe   = regexp.MustCompile(`(?m)^MESH_NODE_ADDR ([A-Za-z0-9_.-]{1,15}) ([0-9.]{7,15})/[0-9]{1,2}\s*$`)
	connTokenBad = " \t\r\n'\"\\$`;|&<>(){}*?!#~"
)

func validToken(tok string) bool {
	return tok != "" && len(tok) <= 4096 && !strings.ContainsAny(tok, connTokenBad)
}

func connectorHead(act Action, run string) string {
	return fmt.Sprintf(`#!/bin/bash
# Meridian Mesh, fixed action: %s (run %s).
# Generated by the panel; it touches only the official cloudflare-warp
# source, key, package and service, gnupg when gpg is missing, and
# /var/lib/meridian/mesh-deploy/%s.
`, act, run, run)
}

// ConnectorPreflightScript is the read-only check of a host the run will
// install the connector on, run at deploy time on the host itself: tools,
// supported system and architecture, no WARP client already there, memory
// (estimate), the official source reachable from this host, WARP's table
// not used by anything, and on a hub the provisioned Mesh underlay routes.
func ConnectorPreflightScript(run string, role model.Role, codename string) (string, error) {
	if !ValidRunID(run) {
		return "", errors.New("run id 无效")
	}
	if !codenameRe.MatchString(codename) {
		return "", errors.New("发行代号无效；先检测这台主机")
	}
	var sb strings.Builder
	sb.WriteString(connectorHead(ActConnectorPreflight, run))
	fmt.Fprintf(&sb, `set -u
export LC_ALL=C
n=0
c() { echo "MESH_CONFLICT $1 $2"; n=$((n+1)); }
for b in apt-get dpkg-query systemctl curl ip; do
  command -v "$b" >/dev/null 2>&1 || c missing_tool "$b"
done
# gpg is not a blocker: the install adds gnupg from the host's own apt
# sources when it is missing (and the removal purges only that).
command -v gpg >/dev/null 2>&1 || echo "MESH_INFO gpg_install gpg is missing; the install adds the Debian package gnupg from this host's apt sources"
id=$( (. /etc/os-release 2>/dev/null; printf '%%s' "${ID:-}") )
cn=$( (. /etc/os-release 2>/dev/null; printf '%%s' "${VERSION_CODENAME:-}") )
case "$id" in debian|ubuntu) ;; *) c unsupported_os "only Debian / Ubuntu are supported";; esac
[ "$cn" = %[1]s ] || c codename_changed "release codename differs from the detection; detect again"
case "$(uname -m)" in x86_64|aarch64) ;; *) c unsupported_arch "only x86_64 / aarch64 are supported";; esac
if pgrep -x warp-svc >/dev/null 2>&1 || ip link show %[2]s >/dev/null 2>&1 || systemctl is-active --quiet warp-svc.service 2>/dev/null; then
  c host_warp "a WARP client already runs here; detect again (an existing node is reused, never reinstalled)"
fi
kb=$(awk '/^MemAvailable:/{print $2}' /proc/meminfo 2>/dev/null)
[ "${kb:-0}" -ge %[3]d ] || c memory "MemAvailable below the estimated %[4]d MB"
code=$(timeout 10 curl -s -o /dev/null -w '%%{http_code}' --max-time 8 %[5]s 2>/dev/null || true)
[ "$code" = 200 ] || c repo_unreachable "this host does not reach the official package source (HTTP ${code:-none}); nothing is installed"
for f in 4 6; do
  if ! rr=$(ip -N -$f rule show 2>/dev/null); then c rule_read "IPv$f policy rules cannot be read; table %[6]d cannot be checked"; continue; fi
  if printf '%%s\n' "$rr" | grep -q 'lookup %[6]d\b'; then c warp_table "IPv$f routing table %[6]d is already used by a rule"; fi
done
if [ -e /etc/systemd/system/meridian-host.service ] || [ -S /run/meridian-host/agent.sock ]; then c home_gateway "this is the home gateway; Mesh never runs here"; fi
`, shq(codename), model.MeshPendingIface, ConnectorMinMemMB*1024, ConnectorMinMemMB, shq(RepoKeyURL), warpTable)
	if role == model.RoleHub {
		sb.WriteString(`r=/usr/local/sbin/meridian-routes.sh
[ -f "$r" ] || c not_provisioned "$r is missing; provision the hub first"
[ -f "$r" ] && { grep -q 'mesh_underlay()' "$r" || c stale_routes "$r lacks the Mesh underlay routes; re-provision the hub"; }
`)
	}
	sb.WriteString(`echo "MESH_PREFLIGHT_DONE conflicts=$n"
if [ "$n" -eq 0 ]; then echo MESH_PREFLIGHT_OK; exit 0; fi
exit 1
`)
	return sb.String(), nil
}

// repoHost is the official source's origin (host name) for the apt pin.
var repoHost = strings.TrimSuffix(strings.TrimPrefix(RepoURL, "https://"), "/")

// ConnectorInstallScript installs and registers the connector. fpr is the
// pinned signing key fingerprint; the downloaded key must carry exactly it.
// The WARP client is put in connector mode by the registration and never
// asked for a full tunnel; a default route in its table afterwards fails
// the install (and the run's compensation removes what it created).
func ConnectorInstallScript(run, codename, fpr, token string) (string, error) {
	if !ValidRunID(run) {
		return "", errors.New("run id 无效")
	}
	if !codenameRe.MatchString(codename) {
		return "", errors.New("发行代号无效")
	}
	if !fprRe.MatchString(fpr) {
		return "", errors.New("签名公钥指纹没有配置或格式不对")
	}
	if !validToken(token) {
		return "", errors.New("节点令牌为空或含有不允许的字符")
	}
	line := fmt.Sprintf("deb [signed-by=%s] %s %s main", RepoKeyring, RepoURL, codename)
	var sb strings.Builder
	sb.WriteString(connectorHead(ActConnectorInstall, run))
	fmt.Fprintf(&sb, `set -u
export LC_ALL=C DEBIAN_FRONTEND=noninteractive
umask 077
bk=%[1]s
install -d -m 700 /var/lib/meridian/mesh-deploy "$bk" || { echo MESH_INSTALL_FAIL; exit 1; }
tmp=$(mktemp -d) || { echo MESH_INSTALL_FAIL; exit 1; }
trap 'rm -rf "$tmp"' EXIT
# Ownership: before each mutation the prior state and the intent are
# persisted ("$bk/<res>.intent"); a failed marker write stops the install.
# After the mutation succeeds "$bk/<res>.created" follows. The removal
# trusts neither alone: it inspects the actual state and undoes only what
# the intent says this run would add.
intent() { local r=$1; shift; { printf '%%s\n' "$@" > "$bk/$r.intent" && [ -f "$bk/$r.intent" ] && [ -s "$bk/$r.intent" ]; } 2>/dev/null || fail "marker_$r"; sync "$bk/$r.intent" 2>/dev/null || true; echo "MESH_INTENT $r"; }
rec() { : > "$bk/$1.created" || fail "marker_$1"; echo "MESH_CREATED $1"; }
fail() { echo "MESH_INSTALL_FAIL $1" >&2; echo "MESH_INSTALL_FAIL $1"; exit 1; }
# Primary-key fingerprints only (a subkey's fpr follows its sub record).
fpr_of() { gpg --batch --with-colons --show-keys "$1" 2>/dev/null | awk -F: '$1 == "pub" { p = 1; next } $1 == "sub" { p = 0; next } $1 == "fpr" && p { print $10; p = 0 }' | sort -u; }
# 0. gpg verifies the key below. A host without it gets gnupg from its own
# apt sources; the removal purges it (and the packages this install pulled
# in, when recorded) only because the intent says gpg was absent before.
if ! command -v gpg >/dev/null 2>&1; then
  dpkg-query -W -f='${Package}\n' 2>/dev/null | sort -u > "$tmp/pre" || : > "$tmp/pre"
  intent gnupg before=absent
  apt-get install -y --no-install-recommends gnupg >/dev/null 2>&1 || { apt-get update >/dev/null 2>&1 && apt-get install -y --no-install-recommends gnupg >/dev/null 2>&1; } || fail gpg_install
  command -v gpg >/dev/null 2>&1 || fail gpg_install
  dpkg-query -W -f='${Package}\n' 2>/dev/null | sort -u | comm -13 "$tmp/pre" - | grep -E '^[a-z0-9][a-z0-9+.:-]*$' > "$tmp/new" || true
  { cat "$tmp/new" > "$bk/gnupg.pkgs"; } 2>/dev/null || fail marker_gnupg
  rec gnupg
fi
# 1. signing key: an existing keyring must hold exactly the allowed key set
# (the pinned key and nothing else).
if [ -e %[2]s ]; then
  [ "$(fpr_of %[2]s)" = %[3]s ] || fail key_set_differs
else
  curl -fsS --max-time 30 %[4]s -o "$tmp/key.asc" || fail repo_unreachable
  [ "$(fpr_of "$tmp/key.asc")" = %[3]s ] || fail key_fingerprint
  gpg --batch --yes --dearmor -o "$tmp/key.gpg" "$tmp/key.asc" || fail key_install
  intent key before=absent
  install -m 644 "$tmp/key.gpg" %[2]s || fail key_install
  rec key
fi
# 2. source list: an existing one must be exactly the official line, with
# no other source line (comments and blank lines aside).
if [ -e %[5]s ]; then
  [ "$(grep -vE '^[[:space:]]*(#|$)' %[5]s)" = %[6]s ] || fail repo_list_differs
else
  printf '%%s\n' %[6]s > "$tmp/list" || fail repo_install
  intent repo before=absent
  install -m 644 "$tmp/list" %[5]s || fail repo_install
  rec repo
fi
# 3. package. The candidate version is taken from the official list alone;
# the host's own lists are then refreshed as well (not undone on removal)
# so the package's Debian dependencies are installable from the host's
# sources, while a temporary pin admits cloudflare-warp only from the
# official origin (every other origin of it at -1).
if ! dpkg-query -W -f='${Status}' %[7]s 2>/dev/null | grep -q 'install ok installed'; then
  one=(-o Dir::Etc::sourcelist=%[5]s -o Dir::Etc::sourceparts=- -o Dir::Etc::preferencesparts=- -o APT::Get::List-Cleanup=0)
  apt-get "${one[@]}" update || fail apt_update
  ver=$(apt-cache "${one[@]}" madison %[7]s 2>/dev/null | awk -F'|' -v u=%[9]s 'BEGIN { sub(/\/+$/, "", u) } { gsub(/ /, "", $2); s = $3; sub(/^ +/, "", s); if ((s == u || index(s, u " ") == 1 || index(s, u "/") == 1) && $2 != "") { print $2; exit } }')
  [ -n "$ver" ] || fail candidate_not_official
  case "$ver" in *[!A-Za-z0-9.+:~-]*) fail candidate_not_official;; esac
  apt-get update || fail apt_update_host
  printf 'Package: %[7]s\nPin: origin "%[10]s"\nPin-Priority: 1001\n\nPackage: %[7]s\nPin: version *\nPin-Priority: -1\n' > "$tmp/pin" || fail apt_pin
  pin=(-o Dir::Etc::preferences="$tmp/pin" -o Dir::Etc::preferencesparts=-)
  # Installed packages before, so the removal purges exactly what this
  # install added (also when interrupted before package.deps is written).
  { dpkg-query -W -f='${Package}\n' 2>/dev/null | sort -u > "$bk/package.pre" && [ -s "$bk/package.pre" ]; } || fail marker_package
  intent package before=absent
  apt-get "${pin[@]}" install -y --no-install-recommends %[7]s="$ver" || fail apt_install
  [ "$(dpkg-query -W -f='${Version}' %[7]s 2>/dev/null)" = "$ver" ] || fail apt_install_version
  apt-cache "${pin[@]}" policy %[7]s 2>/dev/null | awk -v v="$ver" -v h=%[10]s '$1 == "***" { p = ($2 == v); next } $2 ~ /^(https?:|\/)/ { if (p && $2 ~ ("^https?://" h "(/|$)")) ok = 1; next } { p = 0 } END { exit !ok }' || fail apt_install_origin
  dpkg-query -W -f='${Package}\n' 2>/dev/null | sort -u | comm -13 "$bk/package.pre" - | grep -E '^[a-z0-9][a-z0-9+.:-]*$' | grep -vx %[7]s > "$tmp/deps" || true
  { cat "$tmp/deps" > "$bk/package.deps"; } 2>/dev/null || fail marker_package
  rec package
fi
if ! systemctl is-active --quiet %[8]s; then
  en=no; systemctl is-enabled --quiet %[8]s 2>/dev/null && en=yes
  intent service enabled=$en active=no
  systemctl enable --now %[8]s || fail service
  rec service
fi
# 4. registration as a connector of the panel's Mesh account. The token is
# only in a 0600 file in the 0700 temporary directory, removed on exit.
`, shq(backupDir(run)), shq(RepoKeyring), shq(fpr), shq(RepoKeyURL), shq(RepoList), shq(line), PackageName, ServiceName, shq(RepoURL), repoHost)
	d := heredocDelim(token)
	fmt.Fprintf(&sb, "cat > \"$tmp/token\" <<'%s'\n%s\n%s\nchmod 600 \"$tmp/token\"\n", d, token, d)
	fmt.Fprintf(&sb, `if warp-cli --accept-tos registration show >/dev/null 2>&1; then fail registration_exists; fi
intent registration before=none
warp-cli --accept-tos connector new "$(cat "$tmp/token")" >/dev/null 2>&1 || fail register
rm -f "$tmp/token"
rec registration
warp-cli --accept-tos connect >/dev/null 2>&1 || fail connect
a=""
for i in $(seq 1 30); do
  a=$(ip -4 -o addr show dev %[1]s 2>/dev/null | awk '{print $4}' | grep '^100\.' | head -n 1)
  [ -n "$a" ] && break
  sleep 2
done
[ -n "$a" ] || fail no_mesh_address
# No full tunnel, either family: WARP's table must not carry a default
# route and no default route may leave via its interface.
for f in 4 6; do
  if ip -$f route show table %[2]d 2>/dev/null | grep -q '^default'; then fail global_default_v$f; fi
  # All default routes (no limit); a failed read cannot pass.
  r=$(ip -N -$f route show table all 2>/dev/null) || fail global_default_read_v$f
  if printf '%%s\n' "$r" | grep -E '^default ' | grep -qw 'dev %[1]s'; then fail global_default_v$f; fi
done
echo "MESH_NODE_ADDR %[1]s $a"
echo MESH_INSTALL_OK
`, model.MeshPendingIface, warpTable)
	return sb.String(), nil
}

// ConnectorRemoveScript undoes what the run's connector install created on
// the host, by the markers in its backup directory and nothing else: the
// registration (deleted on the host; the Cloudflare node is deleted through
// the API afterwards), the package and service it installed, the source
// list and the key it added. Each marker is removed once its resource is
// gone, so a retry resumes where a failure stopped. A host with neither the
// backup directory nor the run's "restored" marker reports
// MESH_RESTORE_ABSENT.
func ConnectorRemoveScript(run string) (string, error) {
	if !ValidRunID(run) {
		return "", errors.New("run id 无效")
	}
	var sb strings.Builder
	sb.WriteString(connectorHead(ActConnectorRemove, run))
	fmt.Fprintf(&sb, `set -u
export LC_ALL=C DEBIAN_FRONTEND=noninteractive
bk=%[1]s
if [ ! -d "$bk" ]; then
  if [ -e "$bk.restored" ]; then echo "MESH_RESTORE_OK already restored"; exit 0; fi
  echo "MESH_RESTORE_ABSENT nothing from this run is on the host"
  exit 0
fi
fail=0
has() { [ -e "$bk/$1.created" ] || [ -e "$bk/$1.intent" ]; }
val() { sed -n "s/^$2=//p" "$bk/$1.intent" 2>/dev/null | head -n 1; }
done_() { rm -f "$bk/$1.created" "$bk/$1.intent"; echo "MESH_REMOVED $1"; }
pkg_present() { local st; st=$(dpkg-query -W -f='${Status}' %[3]s 2>/dev/null) || return 1; [ -n "$st" ] && ! printf '%%s' "$st" | grep -q 'not-installed'; }
# 1. registration. It is cleared only when the client confirms it; a
# missing client is never proof, and while it is not confirmed the client
# and everything it depends on (package, service, source, key) stay.
if has registration; then
  reg=0
  if command -v warp-cli >/dev/null 2>&1; then
    warp-cli --accept-tos disconnect >/dev/null 2>&1 || true
    if warp-cli --accept-tos registration delete >/dev/null 2>&1; then
      reg=1
    elif systemctl is-active --quiet %[2]s && ! o=$(warp-cli --accept-tos registration show 2>&1) && printf '%%s' "$o" | grep -qi 'missing registration\|not registered\|no registration'; then
      reg=1
    fi
    [ "$reg" = 1 ] || echo "cannot delete the registration; the client and its package, service, source and key stay" >&2
  else
    echo "MESH_RESTORE_UNVERIFIED registration: warp-cli is missing, the registration cannot be confirmed as deleted" >&2
    echo "MESH_RESTORE_UNVERIFIED registration"
  fi
  if [ "$reg" = 1 ]; then done_ registration; else
    echo "MESH_RESTORE_INCOMPLETE registration"
    echo MESH_RESTORE_FAIL
    exit 1
  fi
fi
# 2. service, when the package itself stays: back to its prior state.
if has service && ! has package; then
  ok=1
  if [ "$(val service active)" != yes ] && systemctl is-active --quiet %[2]s; then systemctl stop %[2]s >/dev/null 2>&1 || ok=0; fi
  if [ "$(val service enabled)" != yes ] && systemctl is-enabled --quiet %[2]s 2>/dev/null; then systemctl disable %[2]s >/dev/null 2>&1 || ok=0; fi
  if [ "$ok" = 1 ]; then done_ service; else echo "cannot stop %[2]s" >&2; fail=1; fi
fi
# 3. package: absent before this run, so whatever of it is there now goes
# (also half-installed or unpacked by an apt-get that then failed).
if has package; then
  if pkg_present; then apt-get purge -y %[3]s >/dev/null 2>&1 || true; fi
  if pkg_present; then echo "cannot purge %[3]s" >&2; fail=1; else
    # Then exactly the dependencies this install added: the recorded list,
    # else (interrupted before it was saved) what is installed now and was
    # not before the install, else nothing more. No autoremove.
    l=""
    if [ -f "$bk/package.deps" ]; then l=$(cat "$bk/package.deps")
    elif [ -s "$bk/package.pre" ]; then l=$(dpkg-query -W -f='${Package}\n' 2>/dev/null | sort -u | comm -13 "$bk/package.pre" -)
    fi
    gp() { local st; st=$(dpkg-query -W -f='${Status}' "$1" 2>/dev/null) || return 1; [ -n "$st" ] && ! printf '%%s' "$st" | grep -q 'not-installed'; }
    p=""; for k in $(printf '%%s\n' $l | grep -E '^[a-z0-9][a-z0-9+.:-]*$' | grep -vx %[3]s); do gp "$k" && p="$p $k"; done
    [ -z "$p" ] || apt-get purge -y $p >/dev/null 2>&1 || true
    left=""; for k in $p; do gp "$k" && left="$left $k"; done
    if [ -n "$left" ]; then echo "cannot purge dependencies:$left" >&2; fail=1; else
      rm -f "$bk/package.deps" "$bk/package.pre"; done_ package; has service && done_ service
    fi
  fi
fi
if [ "$fail" -eq 0 ]; then
  if has repo; then rm -f %[4]s && done_ repo || { echo "cannot remove the source list" >&2; fail=1; }; fi
  if has key; then rm -f %[5]s && done_ key || { echo "cannot remove the key" >&2; fail=1; }; fi
fi
# 4. gnupg, last and only when this run's intent says gpg was absent before:
# gnupg itself plus the packages its install newly pulled in (recorded).
if [ "$fail" -eq 0 ] && has gnupg; then
  if [ "$(val gnupg before)" = absent ]; then
    gp() { local st; st=$(dpkg-query -W -f='${Status}' "$1" 2>/dev/null) || return 1; [ -n "$st" ] && ! printf '%%s' "$st" | grep -q 'not-installed'; }
    l=gnupg; [ -f "$bk/gnupg.pkgs" ] && l="gnupg $(grep -E '^[a-z0-9][a-z0-9+.:-]*$' "$bk/gnupg.pkgs" | grep -vx gnupg | tr '\n' ' ')"
    p=""; for k in $l; do gp "$k" && p="$p $k"; done
    [ -z "$p" ] || apt-get purge -y $p >/dev/null 2>&1 || true
    if gp gnupg; then echo "cannot purge gnupg" >&2; fail=1; else rm -f "$bk/gnupg.pkgs"; done_ gnupg; fi
  else
    rm -f "$bk/gnupg.pkgs"; done_ gnupg
  fi
fi
if [ "$fail" -eq 0 ]; then
  : > "$bk.restored" || { echo MESH_RESTORE_FAIL; exit 1; }
  rm -rf "$bk"
  echo MESH_RESTORE_OK
  exit 0
fi
echo "MESH_RESTORE_INCOMPLETE"
echo MESH_RESTORE_FAIL
exit 1
`, shq(backupDir(run)), ServiceName, PackageName, shq(RepoList), shq(RepoKeyring))
	return sb.String(), nil
}

// ParseCreated returns the resources an install output reports as created.
func ParseCreated(out string) []string {
	seen := map[string]bool{}
	for _, m := range createdRe.FindAllStringSubmatch(out, -1) {
		seen[m[1]] = true
	}
	var res []string
	for _, r := range connectorResources {
		if seen[r] {
			res = append(res, r)
		}
	}
	return res
}

// ParseNodeAddr returns the Mesh address and interface an install reports,
// only when the address is in the Mesh range.
func ParseNodeAddr(out string) (addr, iface string, ok bool) {
	m := nodeAddrRe.FindStringSubmatch(out)
	if m == nil {
		return "", "", false
	}
	ip, err := netip.ParseAddr(m[2])
	if err != nil || !ip.Is4() || !MeshIPRange.Contains(ip) {
		return "", "", false
	}
	return ip.String(), m[1], true
}

// HostPreflightScript checks a host that already is a host-level Mesh node
// (reused or installed by an earlier run): the node's address is still on
// its interface, the hub was provisioned with the Mesh underlay routes, and
// for every leg whose ends are both nodes the WireGuard leg, its listener or
// Endpoint, and the fail-closed host route. Nothing is written.
func HostPreflightScript(run string, p Plan, n NodeTarget) (string, error) {
	if !ValidRunID(run) {
		return "", errors.New("run id 无效")
	}
	if !hostIface(n.MeshIface) {
		return "", errors.New("Mesh 节点的接口名无效")
	}
	ip, e := netip.ParseAddr(n.MeshAddr)
	if e != nil || !ip.Is4() || !MeshIPRange.Contains(ip) {
		return "", errors.New("Mesh 节点的地址无效")
	}
	var sb strings.Builder
	sb.WriteString(connectorHead(ActPreflight, run))
	sb.WriteString(`set -u
n=0
c() { echo "MESH_CONFLICT $1 $2"; n=$((n+1)); }
command -v wg >/dev/null 2>&1 || c missing_tool wg
if [ -e /etc/systemd/system/meridian-host.service ] || [ -S /run/meridian-host/agent.sock ]; then c home_gateway "this is the home gateway; Mesh never runs here"; fi
`)
	fmt.Fprintf(&sb, "ip -4 -o addr show dev %s 2>/dev/null | grep -Fq ' %s/' || c reuse_node 'the Mesh node no longer has its detected address on its interface; detect again'\n", shq(n.MeshIface), ip)
	if n.Role == model.RoleHub {
		sb.WriteString("grep -q 'mesh_underlay()' /usr/local/sbin/meridian-routes.sh 2>/dev/null || c reuse_routes 'meridian-routes.sh lacks WireGuard Mesh underlay routes; re-provision the hub'\n")
	}
	for _, l := range p.Legs {
		if (l.HubID != n.ID && l.ExitID != n.ID) || l.Reuse == ReusePending {
			continue
		}
		addr, e := netip.ParsePrefix(l.Network)
		if e != nil || !addr.Addr().Is4() || addr.Bits() != 32 || !ifaceName(l.Interface) || !strings.HasPrefix(l.Interface, "m") || l.Port < 1 || l.Port > 65535 || l.PathMTU < 1280 || l.DeviceMTU < 1280 || l.PayloadMTU <= 0 {
			return "", errors.New("Mesh 腿预检参数无效")
		}
		iface := shq(l.Interface)
		fmt.Fprintf(&sb, `mtu=$(ip -o link show dev %s 2>/dev/null | sed -n 's/.* mtu \([0-9]*\).*/\1/p')
[ "$mtu" = '%d' ] || c leg_mtu 'WireGuard leg missing or MTU differs; re-provision both ends'
`, iface, l.DeviceMTU)
		if n.Role == model.RoleExit {
			fmt.Fprintf(&sb, "[ \"$(wg show %s listen-port 2>/dev/null)\" = '%d' ] || c leg_udp 'exit WireGuard UDP listener missing or wrong port'\n", iface, l.Port)
		} else {
			fmt.Fprintf(&sb, `wg show %s endpoints 2>/dev/null | awk '{print $2}' | grep -Fxq '%s:%d' || c leg_endpoint 'WireGuard Endpoint differs from the peer Mesh address; re-provision the hub'
routes=$(ip -4 route show table main exact %s 2>/dev/null)
printf '%%s\n' "$routes" | grep -q '^blackhole ' || c leg_blackhole 'peer Mesh address has no fail-closed host route'
if printf '%%s\n' "$routes" | grep -v '^blackhole ' | grep -v '^$' | grep -v 'dev %s' >/dev/null; then c leg_route 'peer Mesh address has a route outside the Mesh interface'; fi
`, iface, addr.Addr(), l.Port, shq(l.Network), n.MeshIface)
		}
		fmt.Fprintf(&sb, "echo 'MESH_CHECK leg_plan PASS Mesh path MTU %d; WireGuard device %d; payload %d; UDP %d'\n", l.PathMTU, l.DeviceMTU, l.PayloadMTU, l.Port)
	}
	sb.WriteString(`echo "MESH_PREFLIGHT_DONE conflicts=$n"
if [ "$n" -eq 0 ]; then echo MESH_PREFLIGHT_OK; exit 0; fi
exit 1
`)
	return sb.String(), nil
}
